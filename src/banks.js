function buildSampleBanks() {
  const TYPES = { c: 'choice', t: 'truefalse', o: 'order', n: 'number', i: 'image' };
  return SAMPLE_SUBJECTS.map(([bankId, name, list]) => ({
    bankId, name: '範例：' + name, author: '好學小學堂', version: 1, builtin: true,
    questions: list.map(([t, question, options, answer, difficulty, explain, image], i) => {
      const raw = { type: TYPES[t], question, options: options || [], answer: answer == null ? '' : answer, difficulty, subject: name, explain, image };
      const { q } = normQuestion(raw);
      q.id = bankId + '-' + String(i + 1).padStart(3, '0');
      return q;
    })
  }));
}
